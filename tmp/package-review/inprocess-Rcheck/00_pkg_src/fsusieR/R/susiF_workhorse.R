#' @title Sum of Single Function
#'
#' @description Implementation of the SuSiF method
#'
#' @details Implementation of the SuSiF method
#'
#'
#' @param obj an object of class susiF
#' @param W a list in which element D contains matrix of wavelet d coefficients and
#'  element C contains the vector of scaling coefficients
#' @param X matrix of size n by p contains the covariates
#'

#' @param verbose If \code{verbose = TRUE}, the algorithm's progress,
#' and a summary of the optimization settings are printed to the
#' console.
#' @param lowc_wc  vector of index of which wavelet coefficients display pathologic distribution
#'
#' @param tol a small, non-negative number specifying the convergence
#' tolerance for the IBSS fitting procedure. The fitting procedure
#' will halt when the difference in the variational lower bound, or
#' \dQuote{ELBO} (the objective function to be maximized), is less
#' than \code{tol}.
#'
#' @param maxit Maximum number of IBSS iterations.
#'
#' @param cov_lev numeric between 0 and 1, corresponding to the
#' expected level of coverage of the cs if not specified set to 0.95
#'
#' @param min_purity minimum purity for estimated credible sets
#' @param init_pi0_w starting value of weight on null compoenent in mixsqp
#'  (between 0 and 1)
#' @param control_mixsqp list of parameter for mixsqp function see  mixsqp package
#' @param  cal_obj logical if set as TRUE compute ELBO for convergence monitoring
#' @param nullweight ASH null-component prior parameter; see \code{\link{susiF}}.
#' @param lowc_wc list of wavelet coefficients that exhibit too little variance
#' @param indx_lst list generated by gen_wavelet_indx for the given level of resolution
#'
#' @param tt output of the cal_Bhat_Shat function, if provided allow skipping the first step of the IBSS
#'
#' @param max_step_EM max_step_EM
#' @param parallel if true use parallel computation
#' @param max_SNP_EM check susiF  description
#' @param cor_small check susiF  description
#' @param is.pois check susiF  description
#' @param estimate_sigma2 Logical; if `FALSE`, keep `obj$sigma2` fixed during
#'   all IBSS updates.
#' @param e threshold value to avoid computing posterior that have low alpha value. Set it to 0 to compute the entire posterio. default value is 0.001
#' @export
susiF.workhorse <- function(obj,
                            W,
                            X,
                            tol,
                            init_pi0_w ,
                            control_mixsqp ,
                            indx_lst,
                            lowc_wc,
                            nullweight,
                            cal_obj,
                            verbose,
                            cov_lev,
                            min_purity,
                            maxit,
                            tt,
                            parallel=FALSE,
                            max_SNP_EM=500,
                            max_step_EM=1,
                            cor_small=FALSE,
                            is.pois=FALSE,
                            e = 0.001,
                            estimate_sigma2=TRUE){

  if (!is.logical(estimate_sigma2) || length(estimate_sigma2) != 1L ||
      is.na(estimate_sigma2))
    stop("`estimate_sigma2` must be TRUE or FALSE")
  if (length(maxit) != 1L || !is.finite(maxit) || maxit < 1L ||
      maxit != floor(maxit)) stop("maxit must be a positive integer")

  Y_f <- cbind(W$D, W$C)
  df <- if (cor_small) nrow(X) - 1L else NULL
  obj$converged <- FALSE
  obj$niter <- 0L
  obj$ELBO <- numeric(0)

  # Even with one effect, the residual variance and learned prior need iteration.
  for (iter in seq_len(maxit)) {
    previous <- obj
    obj$greedy_backfit_update <- FALSE
    for (l in seq_len(obj$L)) {
      if (verbose) print(paste("Fitting effect", l, ", iter", iter))
      residual <- cal_partial_resid(obj, l - 1L, X, W$D, W$C, indx_lst)
      tt <- cal_Bhat_Shat(residual, X, sigma2 = obj$sigma2,
                          lowc_wc = lowc_wc)
      if (is.pois)
        tt$Shat <- update_Shat_pois(tt$Shat, indx_lst, lowc_wc)
      prior <- update_prior(get_G_prior(obj), tpi = get_pi(obj, l))
      em <- EM_pi(prior, tt$Bhat, tt$Shat, indx_lst,
                  init_pi0_w = init_pi0_w, control_mixsqp = control_mixsqp,
                  lowc_wc = lowc_wc, nullweight = nullweight,
                  max_SNP_EM = max_SNP_EM, max_step = max_step_EM, df = df,
                  tol_null_prior = obj$tol_null_prior)
      obj <- update_susiF_obj(obj, l, em, tt$Bhat, tt$Shat, indx_lst,
                              lowc_wc = lowc_wc, df = df,
                              cov_lev = cov_lev, e = e)
      if (cal_obj) {
        # Compute KL before another update changes this posterior's residual
        # or noise variance; the stored Bayes factor refers to this update.
        obj$KL[l] <- cal_KL_l(obj, l, X, W$D, W$C, indx_lst)
      }
    }

    obj <- greedy_backfit(obj, verbose, cov_lev, X, min_purity,
                           allow_expand = iter < maxit)
    if (estimate_sigma2)
      obj <- update_residual_variance(
        obj, estimate_residual_variance(obj, Y_f, X))

    same_effects <- obj$L == previous$L && !obj$greedy_backfit_update
    check <- Inf
    if (same_effects) {
      # Alpha alone cannot detect convergence for one SNP or a null effect.
      scale <- max(sqrt(previous$sigma2), abs(unlist(previous$fitted_wc)))
      check <- max(
        abs(unlist(obj$alpha) - unlist(previous$alpha)),
        abs(unlist(obj$est_pi) - unlist(previous$est_pi)),
        abs(unlist(obj$fitted_wc) - unlist(previous$fitted_wc)) / scale,
        abs(obj$sigma2 - previous$sigma2) /
          max(obj$sigma2, previous$sigma2))
    }
    if (cal_obj && !obj$greedy_backfit_update) {
      value <- get_objective(obj, Y_f, X, W$D, W$C, indx_lst) +
        .fs_prior_penalty(obj$est_pi, nullweight)
      obj$ELBO <- c(obj$ELBO, value)
      if (same_effects && length(obj$ELBO) > 1L)
        check <- abs(diff(tail(obj$ELBO, 2L)))
    }
    obj$check <- check
    obj$niter <- iter
    if (is.finite(check) && check <= tol) {
      obj$converged <- TRUE
      break
    }
  }
  obj
}
